import { api, type Profile, type WeeklyPlan } from "./api";
import { leadFavourite, needInfo, SLOT, VERDICT } from "./lib";

// Person-centred activity evidence for inspections (US CMS F679, UK CQC "responsive"):
// every planned activity with why it fits this person (Qloo), the care rules applied (Hearth)
// and staff feedback. Built in the browser; nothing extra is stored.
const cell = (v: unknown) => `"${String(v ?? "").replace(/"/g, '""')}"`;

export async function downloadEvidence(plan: WeeklyPlan, profile: Profile, homeName: string) {
  const hist = await api.history(profile.resident_id).catch(() => []);
  const fb = new Map<string, string>();
  for (const h of hist) if (!fb.has(h.entity_id)) fb.set(h.entity_id, `${h.enjoyed ? "Enjoyed" : "Didn't enjoy"} (${h.created_at.slice(0, 10)})`);
  const rows: unknown[][] = [[
    "Home", "Resident", "Day", "Time", "Activity", "Planned", "Qloo fit", "Why it fits this person (Qloo)",
    "Care needs checked (Hearth rules)", "Staff notes", "Staff feedback",
  ]];
  for (const it of plan.items) {
    const lead = leadFavourite(it.check);
    const why = it.slot === "meal_theme"
      ? (it.evidence_places.length ? `Cuisine from places Qloo ranks highest for them, e.g. ${it.evidence_places.join(", ")}` : "")
      : [lead ? `Linked to their favourite ${lead.name}` : "", ...(it.check?.evidence?.shared_tags || []).slice(0, 3).map((t) => t.name)].filter(Boolean).join("; ");
    const rules = it.rules.map((r) => `${needInfo(r.need).label}: ${r.outcome}${r.outcome !== "pass" ? ` (${r.reason})` : ""}`).join("; ")
      || (it.slot === "meal_theme" && profile.needs.length ? "Dishes filtered for food needs" : "");
    rows.push([
      homeName, profile.name, it.day, SLOT[it.slot]?.time, SLOT[it.slot]?.label, it.title,
      it.check ? `${VERDICT[it.check.verdict].label}${it.check.evidence?.relative_fit != null ? ` ${Math.round(it.check.evidence.relative_fit * 100)}%` : ""}` : "",
      why, rules, it.notes.join("; "), it.entity ? fb.get(it.entity.id) || "" : "",
    ]);
  }
  rows.push([]);
  rows.push(["Recorded care needs", profile.needs.map((n) => needInfo(n).label).join("; ") || "None"]);
  rows.push(["Generated by Hearth", new Date().toISOString().slice(0, 16).replace("T", " ")]);
  const csv = rows.map((r) => r.map(cell).join(",")).join("\r\n");
  const url = URL.createObjectURL(new Blob(["\ufeff" + csv], { type: "text/csv;charset=utf-8" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = `${profile.name.replace(/\W+/g, "-")}-activity-evidence.csv`;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}
